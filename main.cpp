void task_if3()
{
    int number; // ціле число, яке вводить користувач

    cout << "************* If 3 *************" << endl;
    cout << "Введіть ціле число: ";
    cin >> number;

    // перевірка коректності введення: потік cin у нормальному стані
    // і після числа немає зайвих символів (наприклад, "3.5" або "5abc")
    if (!cin || cin.peek() != '\n')
    {
        cout << "Помилка: потрібно ввести ціле число!" << endl;
        return; // вихід з функції
    }

    // повна форма розгалуження з трьома гілками
    if (number > 0)      // число додатне
    {
        number -= 8;     // відняти 8
    }
    else if (number < 0) // число від'ємне
    {
        number += 6;     // додати 6
    }
    else                 // число дорівнює нулю
    {
        number = 10;     // замінити на 10
    }

    cout << "Отримане число: " << number << endl;
}

