// Завдання 1, задача If38 - реалізація
// ---------------------------------------------------------------
void task_if38()
{
    double x;  // аргумент функції (дійсне число)
    int r;     // значення функції r(x) (за умовою - цілого типу)

    cout << "************* If 38 *************" << endl;
    cout << "Введіть дійсне число x: ";
    cin >> x;

    // перевірка коректності введення
    if (!cin || cin.peek() != '\n')
    {
        cout << "Помилка: потрібно ввести число!" << endl;
        return;
    }

    // вибір формули залежно від проміжку, в який потрапляє x;
    // static_cast<int> відкидає дробову частину, бо r - цілого типу
    if (x < -2)        // x належить (-нескінч.; -2)
    {
        r = static_cast<int>(x * x - 4);
    }
    else if (x <= 2)   // x належить [-2; 2]
    {
        r = static_cast<int>(x);
    }
    else               // x належить (2; +нескінч.)
    {
        r = 4;
    }

    cout << "r(" << x << ") = " << r << endl;
}

