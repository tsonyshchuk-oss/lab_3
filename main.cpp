// Завдання 2, геометрична область №31 - реалізація
// ---------------------------------------------------------------
// Розташування фігури: коло радіуса r з центром у точці (-r; 0),
// яке торкається осі OY у початку координат.
// Область 31 складається з двох частин:
//  1) трикутник з вершинами (-2r; 0), (-r; r), (-r; 0);
//  2) сегмент кола, відсічений хордою від точки (-r; r)
//     до точки (0; 0), яка лежить на прямій y = -x.
// Точки на межі області вважаються такими, що належать їй.
void task_geom31()
{
    double radius; // радіус кола
    double x, y;   // координати точки

    cout << "*********** Геометрична область 31 ***********" << endl;
    cout << "Введіть радіус кола r: ";
    cin >> radius;

    // перевірка: має бути число і радіус має бути додатним
    if (!cin || radius <= 0)
    {
        cout << "Некоректні дані! Радіус має бути додатним числом." << endl;
        return;
    }

    cout << "Введіть координати точки (x y): ";
    cin >> x >> y;

    if (!cin) // перевірка: чи введено два числа
    {
        cout << "Не числові дані!" << endl;
        return;
    }

    double xc = -radius, yc = 0;                     // центр кола
    double circle = pow(x - xc, 2) + pow(y - yc, 2); // квадрат відстані до центру
    double R2 = radius * radius;                     // квадрат радіуса

    // частина 1: трикутник - не нижче осі OX, не правіше прямої x = -r
    // і не вище похилої сторони y = x + 2r
    bool inTriangle = y >= 0 && x <= -radius && y <= x + 2 * radius;

    // частина 2: сегмент - всередині кола, не нижче осі OX
    // і правіше (вище) хорди y = -x, тобто x + y >= 0
    bool inSegment = circle <= R2 && y >= 0 && x + y >= 0;

    if (inTriangle || inSegment)
    {
        cout << "Точка належить області 31." << endl;
    }
    else
    {
        cout << "Точка НЕ належить області 31." << endl;
    }
}
